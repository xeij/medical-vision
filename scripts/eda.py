"""Exploratory summary of every dataset with metadata on disk -> reports/eda.md."""

from pathlib import Path

import pandas as pd
import yaml

from data.labels import LABELS, PATHOLOGIES

SPLITS = ["train", "val", "test"]


def md(df: pd.DataFrame) -> str:
    df = df.reset_index()
    rows = ["| " + " | ".join(map(str, df.columns)) + " |", "|" + "---|" * len(df.columns)]
    rows += ["| " + " | ".join(map(str, r)) + " |" for r in df.itertuples(index=False)]
    return "\n".join(rows)


def summarise(name: str, df: pd.DataFrame, info_csv: Path) -> str:
    out = [f"## {name}\n"]
    g = df.groupby("split")
    per_patient = {s: d.groupby("patient_id").size() for s, d in g}
    size = pd.DataFrame(
        {
            "images": g.size(),
            "patients": g["patient_id"].nunique(),
            "images/patient (mean)": {s: round(v.mean(), 2) for s, v in per_patient.items()},
            "images/patient (max)": {s: v.max() for s, v in per_patient.items()},
        }
    ).reindex(SPLITS)
    out += ["### Size per split\n", md(size.rename_axis("split")), ""]

    prev = {}
    for split, d in g:
        col = {lab: f"{int(d[lab].sum())} ({100 * d[lab].mean():.1f}%)" for lab in LABELS}
        anyp = d[list(PATHOLOGIES)].any(axis=1)
        col["any of the 5 pathologies"] = f"{int(anyp.sum())} ({100 * anyp.mean():.1f}%)"
        other = ~anyp & (d["no_finding"] == 0)
        col["other finding only (all six = 0)"] = f"{int(other.sum())} ({100 * other.mean():.1f}%)"
        prev[split] = col
    table = pd.DataFrame(prev)[SPLITS].rename_axis("label")
    out += ["### Label prevalence per split, count (% of split)\n", md(table), ""]

    out += [
        "### View position per split\n",
        md(pd.crosstab(df["split"], df["view"]).reindex(SPLITS)),
        "",
    ]

    age = pd.to_numeric(df["age"], errors="coerce")
    sex = df["sex"].astype(str).str.upper().str[0]
    out += [
        "### Demographics\n",
        f"- age: median {age.median():.0f}, IQR {age.quantile(0.25):.0f}-{age.quantile(0.75):.0f}, "
        f"missing {age.isna().sum()}, implausible (>100) {(age > 100).sum()}",
        f"- sex: F {(sex == 'F').mean() * 100:.1f}%, M {(sex == 'M').mean() * 100:.1f}%, "
        f"other/missing {(~sex.isin(['F', 'M'])).mean() * 100:.1f}%",
        "",
    ]

    if info_csv.exists():
        info = pd.read_csv(info_csv, dtype={"image_id": str})
        sizes = info.groupby(["width", "height", "mode"]).size().rename("images")
        sizes = sizes.sort_values(ascending=False).reset_index().head(15).set_index("width")
        out += [
            f"### Original image sizes ({len(info)} of {len(df)} images converted)\n",
            md(sizes),
            "",
        ]
    else:
        out += ["### Original image sizes\n", "images not downloaded yet", ""]
    return "\n".join(out)


OVERLAP_NOTES = """## Overlap and leakage concerns

- **Patients across datasets.** NIH ChestX-ray14 (NIH Clinical Center, USA) and VinDr-CXR (two
  hospitals in Hanoi, Vietnam) share no patients, so cross-dataset evaluation has no patient
  leakage.
- **Within NIH.** Follow-up images mean several images per patient; the official train_val/test
  lists are patient-disjoint and validation is carved at the patient level.
- **Within VinDr.** No patient identifier is released; splits are image-level by necessity.
- **Encoder pretraining.** The public RAD-DINO checkpoint was pretrained on all 112,120 NIH images
  (plus CheXpert, MIMIC-CXR, PadChest, BRAX), so NIH is not an unseen hospital for RAD-DINO.
  VinDr is unseen by every encoder in the study; VinDr-as-held-out is the clean direction.
- **Label source.** NIH labels are NLP-mined from reports, VinDr labels are radiologist-assigned.
  Cross-dataset degradation mixes image shift with label-quality shift (see LABELS.md).
"""


def main():
    cfg = yaml.safe_load(open("configs/data.yaml"))
    meta_dir = Path(cfg["artifacts_dir"]) / "metadata"
    parts = ["# EDA\n", "Generated by `make eda` from `artifacts/metadata/*.parquet`.\n"]
    for p in sorted(meta_dir.glob("*.parquet")):
        df = pd.read_parquet(p)
        parts.append(summarise(p.stem, df, Path(cfg["datasets_dir"]) / p.stem / "image_info.csv"))
    parts.append(OVERLAP_NOTES)
    Path("reports").mkdir(exist_ok=True)
    Path("reports/eda.md").write_text("\n".join(parts))
    print("\n".join(parts))


if __name__ == "__main__":
    main()
